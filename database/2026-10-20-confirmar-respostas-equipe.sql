-- #310.1 (2026-10-20): "Confirmar Respostas" da equipe. As respostas do líder da equipe (👑,
-- equipe_membro.lider) passam a ser as respostas de todos os membros da equipe na atividade
-- ligada (equipe_atividade), SOBRESCREVENDO as dos membros (decisão do professor, etapa 439).
--  - Quem pode: o líder da equipe (só a própria equipe) e o professor da turma (todas, ou uma
--    pelo 2º parâmetro). Outros: erro 42501.
--  - Antes de apagar, cada linha dos membros vai para backup_clone_equipe (restaurável por SQL).
--  - Entrega: a dos membros nunca é apagada; se o líder entregou, quem não tem entrega
--    recebe a dele.
--  - Líder sem nenhuma resposta: o líder recebe erro; para o professor a equipe é pulada.
-- Substitui a versão da #307.2 (que nunca sobrescrevia). Idempotente.

CREATE TABLE IF NOT EXISTS public.backup_clone_equipe (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    executado_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    executado_por UUID NULL,
    equipe_id     BIGINT NOT NULL,
    atividade_id  BIGINT NOT NULL,
    aluno_id      UUID NOT NULL,
    tabela        TEXT NOT NULL,
    linha         JSONB NOT NULL
);
ALTER TABLE public.backup_clone_equipe ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.backup_clone_equipe FROM anon, authenticated;

-- Quantas respostas (prática + objetiva) o aluno tem na atividade.
CREATE OR REPLACE FUNCTION public.total_respostas_aluno(p_aluno UUID, p_atividade BIGINT)
RETURNS BIGINT
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT (SELECT count(*) FROM public.resposta_discursiva
            WHERE aluno_id = p_aluno AND atividade_id = p_atividade)
         + (SELECT count(*) FROM public.resposta_atividade
            WHERE aluno_id = p_aluno AND atividade_id = p_atividade);
$$;

-- Copia para backup, apaga e recria as respostas de um membro a partir das do líder.
CREATE OR REPLACE FUNCTION public.sobrescrever_respostas_membro(
    p_equipe BIGINT, p_atividade BIGINT, p_lider UUID, p_membro UUID)
RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    INSERT INTO public.backup_clone_equipe
        (executado_por, equipe_id, atividade_id, aluno_id, tabela, linha)
    SELECT auth.uid(), p_equipe, p_atividade, p_membro, 'resposta_discursiva', to_jsonb(r)
    FROM public.resposta_discursiva r
    WHERE r.aluno_id = p_membro AND r.atividade_id = p_atividade;
    INSERT INTO public.backup_clone_equipe
        (executado_por, equipe_id, atividade_id, aluno_id, tabela, linha)
    SELECT auth.uid(), p_equipe, p_atividade, p_membro, 'resposta_atividade', to_jsonb(r)
    FROM public.resposta_atividade r
    WHERE r.aluno_id = p_membro AND r.atividade_id = p_atividade;

    DELETE FROM public.resposta_discursiva WHERE aluno_id = p_membro AND atividade_id = p_atividade;
    DELETE FROM public.resposta_atividade WHERE aluno_id = p_membro AND atividade_id = p_atividade;

    INSERT INTO public.resposta_discursiva
        (aluno_id, atividade_id, tentativa, item, topico, texto, atualizado_em)
    SELECT p_membro, r.atividade_id, r.tentativa, r.item, r.topico, r.texto, now()
    FROM public.resposta_discursiva r
    WHERE r.aluno_id = p_lider AND r.atividade_id = p_atividade;
    INSERT INTO public.resposta_atividade (aluno_id, atividade_id, tentativa, item, letra, herdada)
    SELECT p_membro, r.atividade_id, r.tentativa, r.item, r.letra, r.herdada
    FROM public.resposta_atividade r
    WHERE r.aluno_id = p_lider AND r.atividade_id = p_atividade;

    INSERT INTO public.entrega_atividade
        (aluno_id, atividade_id, entregue_em, tentativa, entregue_por)
    SELECT p_membro, e.atividade_id, e.entregue_em, e.tentativa, auth.uid()
    FROM public.entrega_atividade e
    WHERE e.aluno_id = p_lider AND e.atividade_id = p_atividade
    ON CONFLICT DO NOTHING;
END;
$$;

DROP FUNCTION IF EXISTS public.clonar_respostas_equipe(BIGINT);

CREATE OR REPLACE FUNCTION public.clonar_respostas_equipe(
    p_atividade BIGINT, p_equipe BIGINT DEFAULT NULL)
RETURNS TABLE (equipe_id BIGINT, respondente_id UUID, alunos_clonados INT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_ligacao RECORD;
    v_eh_professor BOOLEAN;
    v_eh_lider BOOLEAN;
    v_respondente UUID;
    v_membro UUID;
    v_clonados INT;
    v_permitidas INT := 0;
BEGIN
    FOR v_ligacao IN
        SELECT ea.id, ea.equipe_id, eq.turma_codigo
        FROM public.equipe_atividade ea
        JOIN public.equipe eq ON eq.id = ea.equipe_id
        WHERE ea.atividade_id = p_atividade AND (p_equipe IS NULL OR ea.equipe_id = p_equipe)
        ORDER BY ea.equipe_id
    LOOP
        v_eh_professor := public.professor_tem_turma(v_ligacao.turma_codigo);
        v_eh_lider := EXISTS (SELECT 1 FROM public.equipe_membro m
                              WHERE m.equipe_id = v_ligacao.equipe_id
                                AND m.aluno_id = auth.uid() AND m.lider);
        CONTINUE WHEN NOT (v_eh_professor OR v_eh_lider);
        v_permitidas := v_permitidas + 1;

        IF v_eh_lider THEN
            v_respondente := auth.uid();
        ELSE
            SELECT m.aluno_id INTO v_respondente FROM public.equipe_membro m
            WHERE m.equipe_id = v_ligacao.equipe_id AND m.lider LIMIT 1;
            v_respondente := coalesce(v_respondente,
                public.escolher_respondente_equipe(v_ligacao.equipe_id, p_atividade));
        END IF;

        v_clonados := 0;
        IF v_respondente IS NULL
           OR public.total_respostas_aluno(v_respondente, p_atividade) = 0 THEN
            IF v_eh_lider AND NOT v_eh_professor THEN
                RAISE EXCEPTION 'O líder ainda não tem respostas nesta atividade.'
                    USING ERRCODE = 'P0001';
            END IF;
            equipe_id := v_ligacao.equipe_id; respondente_id := v_respondente;
            alunos_clonados := 0;
            RETURN NEXT;
            CONTINUE;
        END IF;

        UPDATE public.equipe_atividade SET respondente_id = v_respondente
        WHERE id = v_ligacao.id;

        FOR v_membro IN
            SELECT m.aluno_id FROM public.equipe_membro m
            WHERE m.equipe_id = v_ligacao.equipe_id AND m.aluno_id <> v_respondente
        LOOP
            PERFORM public.sobrescrever_respostas_membro(
                v_ligacao.equipe_id, p_atividade, v_respondente, v_membro);
            v_clonados := v_clonados + 1;
        END LOOP;

        equipe_id := v_ligacao.equipe_id;
        respondente_id := v_respondente;
        alunos_clonados := v_clonados;
        RETURN NEXT;
    END LOOP;

    IF v_permitidas = 0 THEN
        RAISE EXCEPTION 'Sem permissão: só o líder da equipe ou o professor da turma confirmam.'
            USING ERRCODE = '42501';
    END IF;
END;
$$;

-- Atividades ligadas às equipes do aluno logado na matéria (e se ele é o líder da equipe).
CREATE OR REPLACE FUNCTION public.atividades_da_minha_equipe(p_materia BIGINT)
RETURNS TABLE (equipe_id BIGINT, atividade_id BIGINT, nome_atividade TEXT, eu_lider BOOLEAN)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT ea.equipe_id, ea.atividade_id, a.nome_atividade::text, me.lider
    FROM public.equipe_atividade ea
    JOIN public.equipe e ON e.id = ea.equipe_id AND e.materia_id = p_materia
    JOIN public.equipe_membro me ON me.equipe_id = e.id AND me.aluno_id = auth.uid()
    JOIN public.atividade a ON a.id = ea.atividade_id
    ORDER BY ea.equipe_id, a.nome_atividade;
$$;

REVOKE ALL ON FUNCTION public.total_respostas_aluno(UUID, BIGINT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.sobrescrever_respostas_membro(BIGINT, BIGINT, UUID, UUID)
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.clonar_respostas_equipe(BIGINT, BIGINT) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.atividades_da_minha_equipe(BIGINT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.clonar_respostas_equipe(BIGINT, BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.atividades_da_minha_equipe(BIGINT) TO authenticated;
