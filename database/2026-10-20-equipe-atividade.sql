-- #307.1 (2026-10-20): liga uma equipe a uma atividade feita em grupo. O respondente é o aluno
-- da equipe cujas respostas valem para todos (a #307.2 clona as respostas dele para os demais).
-- RLS igual ao das equipes: o professor da turma grava e lê; o aluno líder da turma lê; o aluno
-- lê só as linhas da própria equipe. anon sem acesso. Idempotente.

CREATE TABLE IF NOT EXISTS public.equipe_atividade (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipe_id      BIGINT NOT NULL REFERENCES public.equipe(id) ON DELETE CASCADE,
    atividade_id   BIGINT NOT NULL REFERENCES public.atividade(id) ON DELETE CASCADE,
    respondente_id UUID NULL,
    criado_em      TIMESTAMPTZ NOT NULL DEFAULT now(),
    criado_por     UUID NULL DEFAULT auth.uid(),
    CONSTRAINT equipe_atividade_unica UNIQUE (equipe_id, atividade_id)
);

CREATE INDEX IF NOT EXISTS equipe_atividade_atividade_idx
    ON public.equipe_atividade (atividade_id);

ALTER TABLE public.equipe_atividade ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.equipe_atividade FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.equipe_atividade TO authenticated;

-- Turma da equipe da linha (security definer para a política não depender do RLS de equipe).
CREATE OR REPLACE FUNCTION public.equipe_atividade_turma(p_equipe BIGINT)
RETURNS TEXT
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT turma_codigo FROM public.equipe WHERE id = p_equipe;
$$;

-- O aluno logado é membro da equipe?
CREATE OR REPLACE FUNCTION public.aluno_da_equipe(p_equipe BIGINT)
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.equipe_membro
        WHERE equipe_id = p_equipe AND aluno_id = auth.uid()
    );
$$;

REVOKE ALL ON FUNCTION public.equipe_atividade_turma(BIGINT) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.aluno_da_equipe(BIGINT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.equipe_atividade_turma(BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.aluno_da_equipe(BIGINT) TO authenticated;

DROP POLICY IF EXISTS equipe_atividade_select_professor ON public.equipe_atividade;
CREATE POLICY equipe_atividade_select_professor ON public.equipe_atividade
    FOR SELECT TO authenticated
    USING (professor_tem_turma(equipe_atividade_turma(equipe_id)));

DROP POLICY IF EXISTS equipe_atividade_insert_professor ON public.equipe_atividade;
CREATE POLICY equipe_atividade_insert_professor ON public.equipe_atividade
    FOR INSERT TO authenticated
    WITH CHECK (professor_tem_turma(equipe_atividade_turma(equipe_id)));

DROP POLICY IF EXISTS equipe_atividade_update_professor ON public.equipe_atividade;
CREATE POLICY equipe_atividade_update_professor ON public.equipe_atividade
    FOR UPDATE TO authenticated
    USING (professor_tem_turma(equipe_atividade_turma(equipe_id)))
    WITH CHECK (professor_tem_turma(equipe_atividade_turma(equipe_id)));

DROP POLICY IF EXISTS equipe_atividade_delete_professor ON public.equipe_atividade;
CREATE POLICY equipe_atividade_delete_professor ON public.equipe_atividade
    FOR DELETE TO authenticated
    USING (professor_tem_turma(equipe_atividade_turma(equipe_id)));

DROP POLICY IF EXISTS equipe_atividade_select_lider ON public.equipe_atividade;
CREATE POLICY equipe_atividade_select_lider ON public.equipe_atividade
    FOR SELECT TO authenticated
    USING (aluno_lider_da_turma(equipe_atividade_turma(equipe_id)));

DROP POLICY IF EXISTS equipe_atividade_select_membro ON public.equipe_atividade;
CREATE POLICY equipe_atividade_select_membro ON public.equipe_atividade
    FOR SELECT TO authenticated
    USING (aluno_da_equipe(equipe_id));
