-- #333.2 (2026-10-21): votação das equipes. Na apresentação em sala, o professor abre a votação
-- de uma equipe ligada à atividade (equipe_atividade) e os alunos da turma dão uma nota de 1 a 10.
-- Regras (no banco, não só na tela): 1 voto por aluno em cada equipe, sem trocar; ninguém vota na
-- própria equipe; só com a votação aberta; só aluno da turma da equipe (turmaaluno). O aluno não
-- lê os votos nem a média; o professor da turma vê votos e média.
-- As duas tabelas têm RLS ligado SEM políticas: o acesso é só pelas funções abaixo
-- (security definer, só authenticated). anon sem acesso. Idempotente.

CREATE TABLE IF NOT EXISTS public.votacao_equipe (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atividade_id BIGINT NOT NULL REFERENCES public.atividade(id) ON DELETE CASCADE,
    equipe_id    BIGINT NOT NULL REFERENCES public.equipe(id) ON DELETE CASCADE,
    aberta       BOOLEAN NOT NULL DEFAULT false,
    aberta_em    TIMESTAMPTZ NULL,
    fechada_em   TIMESTAMPTZ NULL,
    criado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
    criado_por   UUID NULL DEFAULT auth.uid(),
    CONSTRAINT votacao_equipe_unica UNIQUE (atividade_id, equipe_id)
);

CREATE TABLE IF NOT EXISTS public.voto_equipe (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    votacao_id BIGINT NOT NULL REFERENCES public.votacao_equipe(id) ON DELETE CASCADE,
    aluno_id   UUID NOT NULL,
    nota       SMALLINT NOT NULL CHECK (nota BETWEEN 1 AND 10),
    criado_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT voto_equipe_unico UNIQUE (votacao_id, aluno_id)
);

ALTER TABLE public.votacao_equipe ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.voto_equipe ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.votacao_equipe FROM anon, authenticated;
REVOKE ALL ON public.voto_equipe FROM anon, authenticated;

-- Professor: abre (p_aberta = true) ou fecha a votação de uma equipe ligada à atividade.
CREATE OR REPLACE FUNCTION public.abrir_votacao_equipe(
    p_atividade BIGINT, p_equipe BIGINT, p_aberta BOOLEAN)
RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.equipe_atividade
                   WHERE equipe_id = p_equipe AND atividade_id = p_atividade) THEN
        RAISE EXCEPTION 'Equipe não está ligada a esta atividade.' USING ERRCODE = '22023';
    END IF;
    IF NOT public.professor_tem_turma(public.equipe_atividade_turma(p_equipe)) THEN
        RAISE EXCEPTION 'Sem permissão: só o professor da turma abre a votação.'
            USING ERRCODE = '42501';
    END IF;
    INSERT INTO public.votacao_equipe AS v (atividade_id, equipe_id, aberta, aberta_em, fechada_em)
    VALUES (p_atividade, p_equipe, p_aberta,
            CASE WHEN p_aberta THEN now() END, CASE WHEN NOT p_aberta THEN now() END)
    ON CONFLICT (atividade_id, equipe_id) DO UPDATE SET
        aberta = EXCLUDED.aberta,
        aberta_em = CASE WHEN EXCLUDED.aberta THEN now() ELSE v.aberta_em END,
        fechada_em = CASE WHEN EXCLUDED.aberta THEN v.fechada_em ELSE now() END;
END;
$$;

-- Professor: uma linha por equipe ligada à atividade, das turmas dele, com votos e média.
CREATE OR REPLACE FUNCTION public.votacoes_equipes_professor(p_atividade BIGINT)
RETURNS TABLE (equipe_id BIGINT, equipe_nome TEXT, turma_codigo TEXT, aberta BOOLEAN,
               votos INTEGER, media NUMERIC)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT e.id, e.nome, e.turma_codigo, COALESCE(v.aberta, false),
           COUNT(vo.id)::INTEGER, ROUND(AVG(vo.nota), 1)
    FROM public.equipe_atividade ea
    JOIN public.equipe e ON e.id = ea.equipe_id
    LEFT JOIN public.votacao_equipe v
        ON v.equipe_id = e.id AND v.atividade_id = ea.atividade_id
    LEFT JOIN public.voto_equipe vo ON vo.votacao_id = v.id
    WHERE ea.atividade_id = p_atividade AND public.professor_tem_turma(e.turma_codigo)
    GROUP BY e.id, e.nome, e.turma_codigo, v.aberta
    ORDER BY e.turma_codigo, e.nome;
$$;

-- Aluno: votações abertas da atividade em que ele pode votar (turma dele, fora da própria
-- equipe), dizendo se já votou. Não devolve votos de ninguém nem a média.
CREATE OR REPLACE FUNCTION public.votacoes_abertas_aluno(p_atividade BIGINT)
RETURNS TABLE (votacao_id BIGINT, equipe_id BIGINT, equipe_nome TEXT, ja_votei BOOLEAN)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT v.id, e.id, e.nome,
           EXISTS (SELECT 1 FROM public.voto_equipe vo
                   WHERE vo.votacao_id = v.id AND vo.aluno_id = auth.uid())
    FROM public.votacao_equipe v
    JOIN public.equipe e ON e.id = v.equipe_id
    WHERE v.atividade_id = p_atividade AND v.aberta
      AND EXISTS (SELECT 1 FROM public.turmaaluno ta
                  WHERE ta.turma_codigo = e.turma_codigo AND ta.aluno_id = auth.uid())
      AND NOT public.aluno_da_equipe(e.id)
    ORDER BY e.nome;
$$;

-- Aluno: grava o voto (1 a 10). Recusa votação fechada, aluno de outra turma, a própria equipe
-- e o segundo voto.
CREATE OR REPLACE FUNCTION public.votar_equipe(p_votacao BIGINT, p_nota INTEGER)
RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_equipe BIGINT;
    v_turma  TEXT;
BEGIN
    IF p_nota IS NULL OR p_nota < 1 OR p_nota > 10 THEN
        RAISE EXCEPTION 'A nota vai de 1 a 10.' USING ERRCODE = '22023';
    END IF;
    SELECT v.equipe_id, e.turma_codigo INTO v_equipe, v_turma
    FROM public.votacao_equipe v JOIN public.equipe e ON e.id = v.equipe_id
    WHERE v.id = p_votacao AND v.aberta;
    IF v_equipe IS NULL THEN
        RAISE EXCEPTION 'A votação desta equipe está fechada.' USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.turmaaluno
                   WHERE turma_codigo = v_turma AND aluno_id = auth.uid()) THEN
        RAISE EXCEPTION 'Só alunos da turma votam.' USING ERRCODE = '42501';
    END IF;
    IF public.aluno_da_equipe(v_equipe) THEN
        RAISE EXCEPTION 'Você não vota na própria equipe.' USING ERRCODE = '42501';
    END IF;
    INSERT INTO public.voto_equipe (votacao_id, aluno_id, nota)
    VALUES (p_votacao, auth.uid(), p_nota);
EXCEPTION
    WHEN unique_violation THEN
        RAISE EXCEPTION 'Você já votou nesta equipe.' USING ERRCODE = '23505';
END;
$$;

REVOKE ALL ON FUNCTION public.abrir_votacao_equipe(BIGINT, BIGINT, BOOLEAN) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.votacoes_equipes_professor(BIGINT) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.votacoes_abertas_aluno(BIGINT) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.votar_equipe(BIGINT, INTEGER) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.abrir_votacao_equipe(BIGINT, BIGINT, BOOLEAN) TO authenticated;
GRANT EXECUTE ON FUNCTION public.votacoes_equipes_professor(BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.votacoes_abertas_aluno(BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.votar_equipe(BIGINT, INTEGER) TO authenticated;

COMMENT ON TABLE public.votacao_equipe IS
  'Votação das equipes (#333): uma por atividade + equipe; acesso só pelas funções.';
COMMENT ON TABLE public.voto_equipe IS
  'Votos de 1 a 10 dos alunos (#333): 1 por aluno e votação; acesso só pelas funções.';
