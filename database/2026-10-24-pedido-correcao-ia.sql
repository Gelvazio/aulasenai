-- Pedido de correção pela IA feito pelo professor no painel (tarefa CORRECAO-IA-PAINEL).
-- O professor registra o pedido (estado PENDENTE); quem corrige e fecha o pedido (CONCLUIDO,
-- concluido_em, total_corrigidas) é o Claude Code local, com service_role/conector.
-- Idempotente; não apaga nem altera dados existentes.

create table if not exists public.pedido_correcao_ia (
  id               bigint      generated by default as identity primary key,
  atividade_id     bigint      not null references public.atividade (id) on delete cascade,
  solicitado_por   uuid        not null default auth.uid(),
  solicitado_em    timestamptz not null default now(),
  estado           text        not null default 'PENDENTE',
  concluido_em     timestamptz,
  total_corrigidas integer,
  constraint pedido_correcao_ia_estado_valido check (estado in ('PENDENTE', 'CONCLUIDO'))
);

create index if not exists pedido_correcao_ia_estado_idx
  on public.pedido_correcao_ia (estado, solicitado_em);

-- Um único pedido PENDENTE por atividade (barra clique duplo e duas abas).
create unique index if not exists pedido_correcao_ia_pendente_uq
  on public.pedido_correcao_ia (atividade_id) where estado = 'PENDENTE';

comment on table public.pedido_correcao_ia is
  'Pedidos de correção pela IA feitos pelo professor; o Claude Code local fecha o pedido.';

alter table public.pedido_correcao_ia enable row level security;
revoke all on public.pedido_correcao_ia from anon;
revoke truncate on public.pedido_correcao_ia from authenticated;
revoke update, delete on public.pedido_correcao_ia from authenticated;
grant select, insert on public.pedido_correcao_ia to authenticated;

drop policy if exists "pedido_correcao_ia_professor_le" on public.pedido_correcao_ia;
create policy "pedido_correcao_ia_professor_le"
  on public.pedido_correcao_ia for select to authenticated
  using (public.eh_professor());

drop policy if exists "pedido_correcao_ia_professor_pede" on public.pedido_correcao_ia;
create policy "pedido_correcao_ia_professor_pede"
  on public.pedido_correcao_ia for insert to authenticated
  with check (
    public.eh_professor()
    and solicitado_por = auth.uid()
    and estado = 'PENDENTE'
  );
